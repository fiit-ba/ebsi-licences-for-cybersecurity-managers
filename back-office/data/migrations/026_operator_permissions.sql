ALTER TABLE operator_accounts
    ADD COLUMN is_staff boolean NOT NULL DEFAULT false,
    ADD COLUMN is_superuser boolean NOT NULL DEFAULT false,
    ADD COLUMN date_joined timestamptz NOT NULL DEFAULT clock_timestamp(),
    ADD COLUMN last_login timestamptz;

CREATE TABLE operator_permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    app_label text NOT NULL,
    model text NOT NULL,
    codename text NOT NULL,
    name text NOT NULL,
    UNIQUE (app_label, model, codename)
);

CREATE TABLE operator_groups (
    id integer PRIMARY KEY CHECK (id > 0),
    name text NOT NULL UNIQUE
);

CREATE TABLE operator_group_permissions (
    group_id integer REFERENCES operator_groups(id) ON DELETE CASCADE,
    permission_id integer REFERENCES operator_permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, permission_id)
);

CREATE TABLE operator_account_groups (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    group_id integer REFERENCES operator_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, group_id)
);

CREATE TABLE operator_account_permissions (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    permission_id integer REFERENCES operator_permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, permission_id)
);

COMMENT ON COLUMN operator_accounts.is_staff IS
    'Administration entry permission. This does not grant registry or governance roles.';
