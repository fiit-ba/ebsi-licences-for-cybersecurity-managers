-- Presentation definitions and flows configure verification requests.
-- Relying parties, mobile bearers and operators have separate result ownership.
-- Requests and results have independent retention; no holder DID or VP is stored.
CREATE TABLE presentation_definitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_id text NOT NULL UNIQUE CHECK (length(definition_id)<=2500),
    format jsonb NOT NULL,
    descriptors jsonb NOT NULL
);

CREATE TABLE verify_flows (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    scope text NOT NULL UNIQUE CHECK (length(scope)<=2000),
    response_type text NOT NULL DEFAULT 'vp_token' CHECK (length(response_type)<=100),
    presentation_definition_id bigint REFERENCES presentation_definitions(id) ON DELETE SET NULL
);

CREATE TABLE relying_parties (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL UNIQUE CHECK (length(name)<=200),
    key_prefix text NOT NULL CHECK (length(key_prefix)<=16),
    key_digest bytea NOT NULL CHECK (octet_length(key_digest)=32),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz
);
CREATE INDEX relying_party_prefix ON relying_parties(key_prefix) WHERE active;

CREATE TABLE presentation_requests (
    state text PRIMARY KEY CHECK (length(state)<=255),
    relying_party_id uuid REFERENCES relying_parties(id) ON DELETE CASCADE,
    -- Security deviation: console results are bound to their requesting account,
    -- rather than shared with every account having a verifier role.
    owner_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    read_token_digest bytea CHECK (octet_length(read_token_digest)=32),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    CHECK (num_nonnulls(relying_party_id,owner_id,read_token_digest)=1)
);

CREATE TABLE presentation_results (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    state text NOT NULL UNIQUE CHECK (length(state)<=255),
    verified boolean NOT NULL,
    outcome text NOT NULL CHECK (length(outcome)<=32),
    detail text NOT NULL DEFAULT '' CHECK (length(detail)<=500),
    credential_types jsonb NOT NULL DEFAULT '[]',
    checks jsonb NOT NULL DEFAULT '{}',
    evidence jsonb NOT NULL DEFAULT '[]',
    attributes_encrypted bytea,
    attributes_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((attributes_encrypted IS NULL)=(attributes_until IS NULL))
);
CREATE INDEX presentation_result_attributes_expiry ON presentation_results(attributes_until)
    WHERE attributes_encrypted IS NOT NULL;

-- Bind protocol nonces to request state; no raw presentation or holder DID is stored.
-- Signed request objects survive a server restart without an ephemeral signer key.
CREATE TABLE presentation_challenges (
    nonce text PRIMARY KEY CHECK (length(nonce)<=2000),
    state text NOT NULL REFERENCES presentation_requests(state) ON DELETE CASCADE,
    flow_scope text NOT NULL CHECK (length(flow_scope)<=2000),
    audience text NOT NULL,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz
);
CREATE INDEX presentation_challenges_state ON presentation_challenges(state);

