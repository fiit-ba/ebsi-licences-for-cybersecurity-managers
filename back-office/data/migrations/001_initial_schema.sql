    requested_at timestamptz NOT NULL,
    requested_by integer NOT NULL,
    tir_completed_at timestamptz,
    licences_completed_at timestamptz,
    attempted_at timestamptz,
    PRIMARY KEY (revoked_organization_id, affected_organization_id)
);

CREATE TABLE issuer_accreditation_checks (
    issuer_did text NOT NULL,
    credential_type text NOT NULL,
    result jsonb NOT NULL,
    PRIMARY KEY (issuer_did, credential_type)
);

CREATE TABLE organization_registration_limits (
    bucket bytea PRIMARY KEY CHECK (octet_length(bucket)=32),
    window_start bigint NOT NULL DEFAULT 0,
    current_count integer NOT NULL DEFAULT 0 CHECK (current_count>=0),
    previous_count integer NOT NULL DEFAULT 0 CHECK (previous_count>=0),
    expires_at timestamptz NOT NULL
);
CREATE INDEX organization_registration_limits_expiry ON organization_registration_limits(expires_at);
COMMENT ON TABLE organization_registration_limits IS
  'Atomic weighted-window registration counters keyed by HMAC address; invitation codes, usernames and raw addresses are never stored.';

-- Keys -----------------------------------------------------------------------------------------

-- Each TI has its own A and B governance keys, capabilityInvocation keys of its DID. Lifecycle
-- dates are recorded from creation; a key is never active once retired.
CREATE TABLE issuer_signing_keys (
    organization_id uuid NOT NULL REFERENCES accredited_organizations(id) ON DELETE RESTRICT,
    kid text NOT NULL CHECK (kid <> ''),
    kms_key_id text NOT NULL CHECK (kms_key_id <> ''),
    public_jwk jsonb NOT NULL CHECK (jsonb_typeof(public_jwk) = 'object' AND NOT (public_jwk ? 'd')),
    active boolean NOT NULL DEFAULT false,
    purpose text NOT NULL DEFAULT 'credential_signing'
        CHECK (purpose IN ('credential_signing', 'did_authentication', 'ledger_transactions',
                           'timestamp_transactions', 'governance_role_a', 'governance_role_b')),
    created_at timestamptz DEFAULT clock_timestamp(),
    activated_at timestamptz,
    retired_at timestamptz,
    PRIMARY KEY (organization_id, kid),
    CONSTRAINT active_keys_not_retired CHECK (NOT active OR retired_at IS NULL),
    CONSTRAINT signing_key_window CHECK (activated_at IS NULL OR retired_at IS NULL OR retired_at >= activated_at)
);
CREATE UNIQUE INDEX one_active_issuer_signing_key
    ON issuer_signing_keys (organization_id, purpose) WHERE active;
CREATE UNIQUE INDEX signing_key_material_not_shared
    ON issuer_signing_keys ((public_jwk->>'kty'), (public_jwk->>'crv'), (public_jwk->>'x'), (public_jwk->>'y'));
COMMENT ON INDEX signing_key_material_not_shared IS
    'One EC public key belongs to one organization and purpose, including retired material.';

CREATE TABLE signing_key_provisions (
    request_id uuid PRIMARY KEY,
    organization_id uuid NOT NULL REFERENCES accredited_organizations(id),
    purpose text NOT NULL
        CHECK (purpose IN ('credential_signing', 'did_authentication', 'ledger_transactions',
                           'timestamp_transactions', 'governance_role_a', 'governance_role_b')),
    phase text NOT NULL DEFAULT 'planned' CHECK (phase IN ('planned', 'started', 'prepared')),
    kms_key_id text,
    kid text,
    requested_by integer REFERENCES operator_accounts(id),
    requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    started_at timestamptz,
    prepared_at timestamptz,
    FOREIGN KEY (organization_id, kid) REFERENCES issuer_signing_keys(organization_id, kid),
    CHECK ((phase = 'prepared') = (kid IS NOT NULL)),
    CHECK (phase <> 'prepared' OR (kms_key_id IS NOT NULL AND prepared_at IS NOT NULL)),
    CHECK ((phase = 'planned') = (started_at IS NULL))
);
COMMENT ON TABLE signing_key_provisions IS
    'Durable ceremony requests. Started requests without a KMS locator require tag-verified recovery; never blindly repeat CreateKey.';

CREATE TABLE organization_key_requests (
    organization_id uuid NOT NULL REFERENCES accredited_organizations(id),
    purpose text NOT NULL,
    request_id uuid NOT NULL UNIQUE REFERENCES signing_key_provisions(request_id),
    PRIMARY KEY (organization_id, purpose)
);

-- One-time ledger signing authorizations bind contract calls to their approved
-- parameters and retain signed transaction bytes for recovery.
CREATE TABLE ledger_signing_intents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    request_key text NOT NULL UNIQUE,
    actor_id integer,
    admin_proposal_id numeric(78,0),
    key_purpose text NOT NULL,
    key_id text NOT NULL,
    signer_address text NOT NULL,
    chain_id bigint NOT NULL CHECK (chain_id > 0),
    contract text NOT NULL,
    contract_function text NOT NULL,
    calldata text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL DEFAULT clock_timestamp() + interval '5 minutes',
    consumed_at timestamptz,
    reconciled_at timestamptz,
    reconciliation_attempted_at timestamptz,
    payload_digest text,
    raw_transaction text,
    transaction_hash text,
    CHECK ((consumed_at IS NULL) = (payload_digest IS NULL)
      AND (consumed_at IS NULL) = (raw_transaction IS NULL)
      AND (consumed_at IS NULL) = (transaction_hash IS NULL))
);
CREATE INDEX ledger_signing_intents_expiry ON ledger_signing_intents(expires_at);
COMMENT ON TABLE ledger_signing_intents IS
    'Exact one-time governance signing authorization; signed bytes survive lost RPC responses and worker restarts. Contains public calldata, never holder claims or preimages.';

-- Only KMS ciphertext belongs in PostgreSQL. Runtime cannot provision a missing key.
CREATE TABLE field_key_setup (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    installation_id uuid NOT NULL DEFAULT gen_random_uuid(),
    creation_started boolean NOT NULL DEFAULT false,
    kms_key_id text
);

CREATE TABLE field_keys (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    installation_id uuid NOT NULL,
    kms_key_id text NOT NULL,
    encryption_wrapped bytea NOT NULL CHECK (octet_length(encryption_wrapped)>32),
    derivation_wrapped bytea NOT NULL CHECK (octet_length(derivation_wrapped)>32),
    legacy_readable boolean NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
COMMENT ON TABLE field_keys IS
    'KMS envelope encryption: independent AES data key and stable PIN/commitment secret, encrypted with installation/purpose context. No plaintext keys.';

CREATE FUNCTION protect_field_keys() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'Field key identity and material cannot be replaced or removed' USING ERRCODE = '55000';
END;
$$;
CREATE TRIGGER field_keys_immutable BEFORE UPDATE OR DELETE ON field_keys
    FOR EACH ROW EXECUTE FUNCTION protect_field_keys();
CREATE TRIGGER field_keys_no_truncate BEFORE TRUNCATE ON field_keys
    FOR EACH STATEMENT EXECUTE FUNCTION protect_field_keys();

