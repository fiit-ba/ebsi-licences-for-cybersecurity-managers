-- Lifecycle ------------------------------------------------------------------------------------

-- Ordinary lifecycle authority follows the current status-manager role. A proposal keeps
-- rejection separately from an earlier approval: a single decision column cannot retain both
-- controls when an approved case is rejected. APPROVED on chain carries executableAt, when it can
-- run. Reason note and salt are AES-GCM envelopes when installation field protection is configured.
CREATE TABLE licence_status_proposals (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    licence_id uuid NOT NULL REFERENCES registered_licences(id) ON DELETE RESTRICT,
    action text NOT NULL CHECK (action IN ('suspend', 'revoke', 'reinstate')),
    initial_standing text NOT NULL CHECK (initial_standing IN ('active', 'suspended')),
    reason_code text NOT NULL,
    reason_note text NOT NULL,
    reason_salt bytea NOT NULL CHECK (octet_length(reason_salt)=32 OR octet_length(reason_salt)>=60),
    reason_hash bytea NOT NULL CHECK (octet_length(reason_hash) = 32),
    proposed_by integer NOT NULL REFERENCES operator_accounts(id),
    proposed_at timestamptz NOT NULL DEFAULT now(),
    decided_by integer REFERENCES operator_accounts(id),
    decided_at timestamptz,
    decision text CHECK (decision IN ('approved', 'rejected')),
    applied_at timestamptz,
    onchain_proposal_id numeric(78,0) CHECK (onchain_proposal_id > 0),
    onchain_contract text,
    onchain_chain_id bigint CHECK (onchain_chain_id > 0),
    onchain_state text NOT NULL DEFAULT 'none'
        CHECK (onchain_state IN ('none', 'proposed', 'approved', 'executed', 'cancelled', 'expired')),
    closed_at timestamptz,
    delivery_attempted_at timestamptz,
    delivery_failed boolean NOT NULL DEFAULT false,
    withdrawal_requested_at timestamptz,
    withdrawn_by integer REFERENCES operator_accounts(id),
    withdrawal_note text,
    withdrawal_salt bytea CHECK (octet_length(withdrawal_salt)=32 OR octet_length(withdrawal_salt)>=60),
    withdrawal_hash bytea CHECK (octet_length(withdrawal_hash) = 32),
    withdrawal_completed_at timestamptz,
    requires_governance boolean NOT NULL DEFAULT true,
    delivery_uncertain boolean NOT NULL DEFAULT false,
    rejected_at timestamptz,
    rejected_by integer REFERENCES operator_accounts(id),
    rejection_delivered_at timestamptz,
    CHECK ((decided_at IS NULL) = (decision IS NULL) AND (decided_by IS NULL) = (decision IS NULL)),
    CHECK (decision <> 'approved' OR decided_by <> proposed_by),
    CHECK (applied_at IS NULL OR decision IS NOT DISTINCT FROM 'approved'),
    CHECK ((onchain_contract IS NULL) = (onchain_chain_id IS NULL)),
    CHECK ((withdrawal_requested_at IS NULL) = (withdrawn_by IS NULL)
      AND (withdrawal_requested_at IS NULL) = (withdrawal_note IS NULL)
      AND (withdrawal_requested_at IS NULL) = (withdrawal_salt IS NULL)
      AND (withdrawal_requested_at IS NULL) = (withdrawal_hash IS NULL)),
    CHECK (withdrawal_requested_at IS NULL OR decision IS NOT DISTINCT FROM 'approved'),
    CHECK (withdrawal_completed_at IS NULL OR (withdrawal_requested_at IS NOT NULL AND closed_at IS NOT NULL))
);
CREATE UNIQUE INDEX one_open_licence_status_proposal ON licence_status_proposals(licence_id)
    WHERE applied_at IS NULL AND closed_at IS NULL AND decision IS DISTINCT FROM 'rejected';
COMMENT ON COLUMN licence_status_proposals.reason_note IS 'private reason note; enc:v1 AES-GCM envelope when installation field encryption is configured.';
COMMENT ON COLUMN licence_status_proposals.reason_salt IS 'private reason salt; AES-GCM envelope authenticated to the public reason commitment when protected.';
COMMENT ON COLUMN licence_status_proposals.requires_governance IS
    'Execution policy captured when the request is proposed; a later runtime change cannot bypass its required governance decision.';
COMMENT ON COLUMN licence_status_proposals.delivery_uncertain IS
    'Durable reconciliation guard set before a delivery attempt; an exactly observed result clears it. Uncertain delivery prevents finalization from using a stale local standing.';
COMMENT ON COLUMN licence_status_proposals.rejected_at IS
    'Closes the case without erasing a previously recorded independent approval. Its on-chain veto is retried separately.';

-- Emergency authority follows the operator's registered organization and role.
