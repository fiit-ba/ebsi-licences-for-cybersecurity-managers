-- Issuance -------------------------------------------------------------------------------------

-- A licence keeps its provisional registration identifier after collection binds it to the UUID
-- minted for the signed credential. Its record on the TAO's CertificateRegistry contract is kept under
-- SHA-256(abi.encode("PLR-CERTIFICATE-V4", TI DID, SHA-256(abi.encode("PLR-CERTIFICATE-ID-V1",
-- vc.id)))), known once the holder collected the credential, together with the hash of the
-- signed JWT. Ledger registration runs after collection commits.
CREATE TABLE registered_licences (
    id uuid PRIMARY KEY,
    credential_id text NOT NULL UNIQUE,
    issuer_id uuid NOT NULL REFERENCES accredited_organizations(id),
    issuer_did text NOT NULL CHECK (issuer_did <> ''),
    issuer_accredited_until timestamptz,
    schema_id uuid NOT NULL,
    schema_version integer NOT NULL,
    licence_number text NOT NULL CHECK (licence_number <> ''),
    status_key bytea UNIQUE CHECK (octet_length(status_key) = 32),
    private_data bytea NOT NULL,
    valid_from timestamptz,
    valid_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by integer NOT NULL,
    ledger_standing text CHECK (ledger_standing IN ('active', 'suspended', 'revoked', 'unknown')),
    ledger_observed_at timestamptz,
    ledger_observation_invalidated_at timestamptz,
    local_standing text NOT NULL DEFAULT 'active'
        CHECK (local_standing IN ('active', 'suspended', 'revoked')),
    registered_id text,
    ledger_registered_at timestamptz,
    credential_hash bytea CHECK (octet_length(credential_hash) = 32),
    UNIQUE (issuer_did, licence_number),
    FOREIGN KEY (schema_id, schema_version) REFERENCES licence_schema_versions(schema_id, version),
    CHECK (valid_until > valid_from),
    CHECK ((ledger_standing IS NULL) = (ledger_observed_at IS NULL)),
    CONSTRAINT collected_record_key CHECK ((status_key IS NULL) = (credential_hash IS NULL))
);
CREATE INDEX registered_licences_issuer_order
    ON registered_licences(issuer_id, created_at DESC, id DESC);
CREATE UNIQUE INDEX registered_licences_registration_id
    ON registered_licences(registered_id) WHERE registered_id IS NOT NULL;
COMMENT ON COLUMN registered_licences.schema_version IS
    'Version used to normalize the registration request. Collection resolves the current published flow version.';
COMMENT ON COLUMN registered_licences.status_key IS
    'V4 record key on the CertificateRegistry contract, from the TI DID and the collected credential id.';
COMMENT ON COLUMN registered_licences.local_standing IS
    'Committed local lifecycle state; authoritative before collection or in explicit local mode. Collected ledger-mode records still require a fresh chain observation.';
COMMENT ON COLUMN registered_licences.registered_id IS
    'Provisional identifier returned by issue before collection; both identifiers find the same licence.';
COMMENT ON COLUMN registered_licences.ledger_registered_at IS
    'Confirmation of initial background registration, independent of subsequent lifecycle standing observations.';
COMMENT ON COLUMN registered_licences.credential_hash IS
    'SHA-256 of the collected credential''s signed JWT (before the first ~), as recorded on chain.';

-- The offer's tx_code says how many digits the separately delivered PIN has.
CREATE TABLE credential_offers (
