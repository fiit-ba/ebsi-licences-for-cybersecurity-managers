-- Operators ----------------------------------------------------------------------------------

CREATE TABLE operator_accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE CHECK (username <> ''),
    email text NOT NULL DEFAULT '',
    password_hash text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    auth_version integer NOT NULL DEFAULT 0 CHECK (auth_version >= 0),
    first_name text NOT NULL DEFAULT '',
    last_name text NOT NULL DEFAULT '',
    is_staff boolean NOT NULL DEFAULT false,
    is_superuser boolean NOT NULL DEFAULT false,
    date_joined timestamptz NOT NULL DEFAULT clock_timestamp(),
    last_login timestamptz
);
CREATE UNIQUE INDEX operator_username_casefold ON operator_accounts (lower(username));
COMMENT ON COLUMN operator_accounts.auth_version IS
    'Session generation; supported administrative changes invalidate previously issued operator JWTs.';
COMMENT ON COLUMN operator_accounts.is_staff IS
    'Administration entry permission. This does not grant registry or governance roles.';

CREATE TABLE operator_roles (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN (
        'plr_admin', 'plr_issuer', 'plr_status_manager', 'plr_verifier',
        'plr_auditor', 'plr_tao', 'plr_rtao'
    )),
    PRIMARY KEY (account_id, role)
);

CREATE TABLE operator_governance_roles (
    account_id integer NOT NULL REFERENCES operator_accounts(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('A', 'B', 'C')),
    PRIMARY KEY (account_id, role)
);
COMMENT ON TABLE operator_governance_roles IS
    'Explicit operator signer-role memberships. Account administration alone grants no ledger signing authority.';

CREATE TABLE operator_permissions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    app_label text NOT NULL,
    model text NOT NULL,
    codename text NOT NULL,
    name text NOT NULL,
    UNIQUE (app_label, model, codename)
);

CREATE TABLE operator_groups (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name text NOT NULL UNIQUE,
    version integer NOT NULL DEFAULT 0 CHECK (version >= 0)
);

CREATE TABLE operator_group_permissions (
    group_id integer REFERENCES operator_groups(id) ON DELETE CASCADE,
    permission_id integer REFERENCES operator_permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (group_id, permission_id)
);

CREATE TABLE operator_account_groups (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    group_id integer REFERENCES operator_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, group_id)
);

CREATE TABLE operator_account_permissions (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    permission_id integer REFERENCES operator_permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (account_id, permission_id)
);

CREATE TABLE operator_password_resets (
    account_id integer REFERENCES operator_accounts(id) ON DELETE CASCADE,
    nonce bytea NOT NULL CHECK (octet_length(nonce) = 32),
    token_digest bytea NOT NULL UNIQUE CHECK (octet_length(token_digest) = 32),
    auth_version integer NOT NULL,
    email text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    expires_at timestamptz NOT NULL,
    requested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    delivered_at timestamptz,
    attempted_at timestamptz,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    purpose text NOT NULL DEFAULT 'recovery' CHECK (purpose IN ('recovery','activation')),
    PRIMARY KEY (account_id, purpose),
    CHECK (expires_at > created_at)
);
CREATE INDEX operator_password_resets_delivery ON operator_password_resets(requested_at)
    WHERE delivered_at IS NULL OR delivered_at < requested_at;
CREATE INDEX operator_password_resets_expiry ON operator_password_resets(expires_at);
COMMENT ON TABLE operator_password_resets IS
  'One outstanding recovery and activation challenge per account; nonce/digest require an external key. Confirmation consumes both purposes.';

CREATE TABLE operator_recovery_limits (
    bucket bytea PRIMARY KEY CHECK (octet_length(bucket) = 32),
    requests timestamptz[] NOT NULL DEFAULT '{}',
    expires_at timestamptz NOT NULL
);
CREATE INDEX operator_recovery_limits_expiry ON operator_recovery_limits(expires_at);
COMMENT ON TABLE operator_recovery_limits IS
    'Shared sliding-window request limits keyed by HMAC; raw client addresses and email addresses are not stored here.';

CREATE TABLE operator_login_limits (
    bucket bytea PRIMARY KEY CHECK (octet_length(bucket)=32),
    attempts integer NOT NULL CHECK (attempts>0),
    expires_at timestamptz NOT NULL
);
CREATE INDEX operator_login_limits_expiry ON operator_login_limits(expires_at);
COMMENT ON TABLE operator_login_limits IS
  'Short-lived HMAC-address login admission windows; no usernames or raw addresses.';

-- Organizations and accreditation ------------------------------------------------------------

-- A TAO or TI is appointed by its own DID, which it registered in the DID Registry itself. Its
-- accreditor reserves its attribute in the Trusted Issuers Registry and signs the accreditation
-- (VerifiableAccreditationToAccredit or ToAttest); the organization downloads it and stores it in
-- the registry with its own wallet. The back-office keeps the credential it issued, to hand over
-- and to recognise in the registry; tir_attribute_id is set once the registry holds it.
--
-- Each TAO has its own CertificateRegistry and governance contract (one pair serves every TI of
-- a TAO), deployed through EBSI's Proxy Factory from the registered templates. The back-office
-- records the pair on the TAO, with the block it was deployed in, where reading its events starts.
-- governance_configured_at says when a TI was set up on its TAO's governance contract (addTi,
-- confirmed).
CREATE TABLE accredited_organizations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL CHECK (btrim(name) <> ''),
    kind text NOT NULL CHECK (kind IN ('rtao', 'tao', 'ti')),
    parent_id uuid,
    parent_kind text GENERATED ALWAYS AS (
        CASE kind WHEN 'tao' THEN 'rtao' WHEN 'ti' THEN 'tao' END
    ) STORED,
    account_id integer UNIQUE REFERENCES operator_accounts(id) ON DELETE SET NULL,
    did text NOT NULL DEFAULT '',
    tir_attribute_id text,
    accredited_until timestamptz,
    revoked_at timestamptz,
    revocation_reason text,
    revocation_note text NOT NULL DEFAULT '',
    contact_email text NOT NULL DEFAULT '',
    selected_by integer REFERENCES operator_accounts(id) ON DELETE SET NULL,
    selected_at timestamptz NOT NULL DEFAULT now(),
    registered_at timestamptz,
    invitation_digest bytea UNIQUE,
    invitation_expires_at timestamptz,
    ebsi_invoke_credential text CHECK (length(ebsi_invoke_credential) <= 16384),
    governance_configured_at timestamptz,
    accreditation_credential text,
    accreditation_issued_at timestamptz,
    governance_contract text CHECK (governance_contract ~ '^0x[0-9a-fA-F]{40}$'),
    certificate_registry text CHECK (certificate_registry ~ '^0x[0-9a-fA-F]{40}$'),
    contracts_block bigint CHECK (contracts_block >= 0),
    contracts_recorded_at timestamptz,
    UNIQUE (id, kind),
    FOREIGN KEY (parent_id, parent_kind) REFERENCES accredited_organizations(id, kind),
    CHECK ((kind = 'rtao') = (parent_id IS NULL)),
    CHECK ((revoked_at IS NULL) = (revocation_reason IS NULL)),
    CHECK ((invitation_digest IS NULL) = (invitation_expires_at IS NULL)),
    CHECK (account_id IS NULL OR invitation_digest IS NULL),
    CONSTRAINT accredited_organizations_tao_contracts CHECK (
        (governance_contract IS NULL AND certificate_registry IS NULL AND contracts_block IS NULL)
        OR (kind = 'tao' AND governance_contract IS NOT NULL AND certificate_registry IS NOT NULL
            AND contracts_block IS NOT NULL)
    )
);
CREATE INDEX accredited_organizations_parent ON accredited_organizations(parent_id);
-- One live organization per DID.
CREATE UNIQUE INDEX accredited_organizations_live_did
    ON accredited_organizations (did)
    WHERE did <> '' AND revoked_at IS NULL;
CREATE UNIQUE INDEX accredited_organizations_governance_contract
    ON accredited_organizations (lower(governance_contract))
    WHERE governance_contract IS NOT NULL;
CREATE UNIQUE INDEX accredited_organizations_certificate_registry
    ON accredited_organizations (lower(certificate_registry))
    WHERE certificate_registry IS NOT NULL;
COMMENT ON COLUMN accredited_organizations.ebsi_invoke_credential IS
    'VerifiableAuthorisationToInvoke the organization presents for ledger:invoke tokens. Public; no private material.';

CREATE TABLE accreditation_events (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    action text NOT NULL,
    organization_id uuid NOT NULL,
    actor_id integer NOT NULL,
